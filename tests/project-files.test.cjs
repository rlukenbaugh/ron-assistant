const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { ProjectFiles } = require('../lib/project-files.cjs');
test('project reads are scoped, bounded, exclude credentials and detect changes', async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'ron-project-'));
  const outside = await fs.mkdtemp(path.join(os.tmpdir(), 'ron-outside-'));
  await fs.writeFile(path.join(root, 'main.cjs'), 'module.exports = 323;');
  await fs.writeFile(path.join(root, '.env'), 'EXAMPLE_KEY=not-a-real-key');
  await fs.writeFile(path.join(root, 'auth.json'), '{}');
  await fs.writeFile(path.join(root, 'big.txt'), 'x'.repeat(65000));
  await fs.writeFile(path.join(root, 'binary.txt'), Buffer.from([1, 0, 2]));
  await fs.writeFile(path.join(outside, 'private.txt'), 'outside');
  await fs.symlink(outside, path.join(root, 'linked'), process.platform === 'win32' ? 'junction' : 'dir');
  const access = new ProjectFiles([{ id: 'source', name: 'Test source', path: root }]);
  const list = await access.publicList();
  assert.ok(list.files.some(f => f.id === 'source:main.cjs'));
  assert.ok(!list.files.some(f => /auth|env|linked/.test(f.id)));
  assert.ok(list.files.every(f => !('full' in f)));
  const snapshot = await access.snapshot(['source:main.cjs']);
  assert.match(snapshot.context, /module.exports = 323/);
  await assert.rejects(access.snapshot(['source:../private.txt']));
  await assert.rejects(access.snapshot(['source:linked/private.txt']));
  await assert.rejects(access.snapshot(['source:big.txt']));
  await assert.rejects(access.snapshot(['source:binary.txt']));
  await fs.writeFile(path.join(root, 'main.cjs'), 'module.exports = 324;');
  assert.notEqual((await access.snapshot(['source:main.cjs'])).files[0].sha256, snapshot.files[0].sha256);
});
